import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import solc from 'solc'
import { keccak256, type Hex } from 'viem'

// Task 05C-1 的已提交工具鏈；不是聲稱已取得歷史部署產物或鏈上匹配證據。
const sourceCommit = '1ed599aef60bc3a110c52910700d843e1081ec9b'
const sha256 = (value: string | Buffer) => createHash('sha256').update(value).digest('hex')
const text = (path: string) => readFileSync(path, 'utf8')
const json = (path: string) => JSON.parse(text(path))
for (const path of ['contracts/TeachingToken.sol', 'hardhat.config.ts', 'package.json', 'package-lock.json']) {
  assert.equal(text(path), execFileSync('git', ['show', `${sourceCommit}:${path}`], { encoding: 'utf8' }), `${path} differs from pinned source commit`)
}
const artifact = json('artifacts/contracts/TeachingToken.sol/TeachingToken.json')
assert.equal(artifact.contractName, 'TeachingToken')
assert.deepEqual(artifact.deployedLinkReferences, {})
assert.deepEqual(artifact.immutableReferences, {})
const build = json(`artifacts/build-info/${artifact.buildInfoId}.json`)
assert.equal(build.id, artifact.buildInfoId, 'Artifact build-info reference mismatch')
const input = build.input
assert.equal(build.solcLongVersion, '0.8.38+commit.1835d247')
assert.equal(solc.version(), '0.8.38+commit.1835d247.Emscripten.clang')
assert.equal(input.settings.evmVersion, 'cancun')
assert.deepEqual(input.settings.optimizer, { enabled: true, runs: 200 })
assert.equal(input.settings.viaIR ?? false, false)
assert.equal(input.settings.metadata, undefined) // Solidity defaults, including IPFS metadata hash.
assert.deepEqual(input.settings.remappings, ['project/:@openzeppelin/contracts/=npm/@openzeppelin/contracts@5.6.1/'])
for (const [path, source] of Object.entries(input.sources) as [string, { content: string }][]) {
  const local = path === 'project/contracts/TeachingToken.sol' ? 'contracts/TeachingToken.sol'
    : path.startsWith('npm/@openzeppelin/contracts@5.6.1/') ? path.replace('npm/@openzeppelin/contracts@5.6.1/', 'node_modules/@openzeppelin/contracts/') : null
  assert.ok(local, `Unexpected source unit: ${path}`)
  assert.equal(source.content, text(local), `Source content mismatch: ${path}`)
}
// 獨立重新編譯完整 input，包含原始 source-unit 路徑、設定及 metadata。
const output = JSON.parse(solc.compile(JSON.stringify(input)))
assert.equal(output.errors?.some((error: { severity: string }) => error.severity === 'error') ?? false, false)
const runtime = `0x${output.contracts['project/contracts/TeachingToken.sol'].TeachingToken.evm.deployedBytecode.object}` as Hex
assert.match(runtime, /^0x(?:[\da-f]{2})+$/i)
assert.equal(runtime.toLowerCase(), artifact.deployedBytecode.toLowerCase(), 'Recompiled runtime differs from Hardhat artifact (including metadata)')
const metadataLength = parseInt(runtime.slice(-4), 16)
assert.ok(metadataLength > 0 && metadataLength + 2 < (runtime.length - 2) / 2, 'Missing Solidity metadata trailer')
// Hardhat buildInfoId 包含本機 solcConfig.path，僅用於尋找產物；不可作為可攜指紋。
const manifest = {
  sourceCommit,
  contract: 'contracts/TeachingToken.sol:TeachingToken',
  compiler: solc.version(),
  openZeppelin: '5.6.1',
  optimizerRuns: 200,
  evmVersion: 'cancun',
  packageLockSha256: sha256(text('package-lock.json')),
  standardJsonInputSha256: sha256(JSON.stringify(input)),
  solcJsSha256: sha256(readFileSync('node_modules/solc/soljson.js')),
  runtimeKeccak256: keccak256(runtime),
  runtimeSize: (runtime.length - 2) / 2,
  includesSolidityMetadata: true,
}
const expected = `// Generated by scripts/contracts/runtime-manifest.ts; do not edit by hand.\nexport const teachingTokenRuntime = ${JSON.stringify(manifest, null, 2)} as const\n`
const destination = 'src/config/teachingTokenRuntime.ts'
if (process.argv.includes('--check')) assert.equal(text(destination), expected, 'Runtime manifest is stale or modified; regenerate and review')
else writeFileSync(destination, expected)
console.log(`Runtime manifest ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${manifest.runtimeKeccak256} (${manifest.runtimeSize} bytes, metadata included)`)
